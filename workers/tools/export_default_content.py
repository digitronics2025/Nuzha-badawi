#!/usr/bin/env python3
"""Export a strict, human-reviewable fallback content manifest from the existing site copy."""
from pathlib import Path
import json
import sys
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'frontend'/'src'/'content'))
from site_copy import COPY
from seo import metadata
mapping={
 'home':['hero','hero_desc','video_title','video_desc','lessons_title','lessons_desc','coaching_title','coaching_desc','services_title','about_title','about_desc','faq_title','closing_title','closing_desc','english','english_desc','russian','russian_desc','arabic','arabic_desc','translation_title','translation_desc','interpretation_title','interpretation_desc'],
 'about':['about_page_title','about_page_desc','story_heading','story_body','journey_title','video_title','video_desc','closing_title','closing_desc'],
 'lessons':['lessons_page_title','lessons_page_desc','english','english_long','russian','russian_long','arabic','arabic_long','process_title','closing_title','closing_desc'],
 'coaching':['coaching_page_title','coaching_page_desc','coaching_title','coaching_desc','closing_title','closing_desc'],
 'translation':['translation_page_title','translation_page_desc','translation_title','translation_desc','interpretation_title','interpretation_desc','process_title','closing_title','closing_desc'],
 'contact':['contact_page_title','contact_page_desc','form_title','closing_desc'],
 'privacy':['privacy_title','privacy_desc','privacy_body']
}
for page, keys in mapping.items():
 if page in ('home','lessons'):
  keys.extend(k for k in COPY['en'] if k.startswith('process_') and (k.endswith('_title') or k.endswith('_body')))
 if page=='home':
  keys.extend(['guide_title','guide_intro','lesson_share','coaching_share','translation_share','interpretation_share']+[f'journey_{i}_{part}' for i in (3,4,2) for part in ('title','body','date')])
 if page=='about':
  keys.extend(f'journey_{i}_{part}' for i in range(7) for part in ('title','body','date'))
mapping['home'].extend([f'faq_{i}_{part}' for i in range(len(COPY['en']['faq'])) for part in ('question','answer')]+[f'proof_{i}' for i in range(3)]+['process_title'])
mapping['coaching'].extend(f'topic_{i}_{part}' for i in range(len(COPY['en']['coaching_topics'])) for part in ('title','body'))
mapping['translation'].extend(f'translation_step_{i}_{part}' for i in range(len(COPY['en']['translation_steps'])) for part in ('title','body'))
out={}
for loc,copy in COPY.items():
 out[loc]={}
 for page,keys in mapping.items():
  title_key='hero' if page=='home' else (page+'_page_title' if page not in ('privacy',) else 'privacy_title')
  desc_key='hero_desc' if page=='home' else (page+'_page_desc' if page not in ('privacy',) else 'privacy_desc')
  out[loc][page]={
   'fields':dict({k:str(copy[k]) for k in keys if k in copy and isinstance(copy[k],str)},**({'title':copy.get(title_key,copy['hero']),'description':copy.get(desc_key,copy['hero_desc'])} if page!='home' else {})),
   'seo':metadata(loc,page),
   'media':{}
  }
destination=ROOT/'workers'/'shared'/'defaults.js'
destination.write_text('// Generated by workers/tools/export_default_content.py. Do not edit manually.\nexport default '+json.dumps(out,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
print('Exported defaults:',destination, len(out),'locales,',sum(len(v) for v in out.values()),'pages')
