// Bundle the generated static frontend into each Worker as an importable module.
// Used instead of Workers Static Assets so deploys need only a script upload (one artifact,
// identical from CI or a workstation). Text is UTF-8; images preserve binary bytes.
import {readdirSync,readFileSync,statSync,writeFileSync} from 'node:fs';
import {join,relative,sep,extname,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const here=dirname(fileURLToPath(import.meta.url));
const TYPES={'.html':'text/html; charset=utf-8','.css':'text/css; charset=utf-8','.js':'text/javascript; charset=utf-8','.svg':'image/svg+xml','.xml':'application/xml; charset=utf-8','.txt':'text/plain; charset=utf-8','.webmanifest':'application/manifest+json; charset=utf-8','.webp':'image/webp','.png':'image/png','.ico':'image/x-icon'};
const BINARY=new Set(['.webp','.png','.ico']);
function bundle(dir,out){
 const files={};
 (function walk(d){for(const f of readdirSync(d).sort()){const p=join(d,f);if(statSync(p).isDirectory()){walk(p);continue;}
   const rel='/'+relative(dir,p).split(sep).join('/');if(rel.endsWith('/_headers'))continue;
   const type=TYPES[extname(p)];if(!type)throw Error(`Unsupported asset type: ${rel}`);
   files[rel]=BINARY.has(extname(p))?{type,base64:readFileSync(p).toString('base64')}:{type,body:readFileSync(p,'utf8')};}})(dir);
 writeFileSync(out,'// GENERATED by tools/bundle_assets.mjs — do not edit.\nexport default '+JSON.stringify(files)+';\n');
 console.log(`Bundled ${Object.keys(files).length} assets -> ${relative(process.cwd(),out)}`);
}
bundle(join(here,'../../frontend/dist-public'),join(here,'../public/src/static-assets.generated.js'));
bundle(join(here,'../../frontend/dist-admin'),join(here,'../admin/src/static-assets.generated.js'));
